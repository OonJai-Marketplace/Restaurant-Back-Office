"""Build the Sales release while retaining the approved 142 shell and login CSS."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
def read(p):return (ROOT/p).read_text()
def write(p,s):(ROOT/p).write_text(s)
core=['vendor/supabase-2.118.0.js','scripts/supabase-config.js','scripts/workspace-config123.js','scripts/restaurant-auth123.js','scripts/restaurant-backoffice.js','scripts/restaurant-permissions125.js','scripts/restaurant-modules125.js','scripts/restaurant-shell122.js','scripts/workspace-links123.js','scripts/restaurant-accounting124.js','scripts/restaurant-home139.js']
write('scripts/restaurant-core143.bundle.js','/* Generated by tools/build-sales143.py. */\nwindow.restaurantBootLoading126=true;\n'+'\n;\n'.join('/* '+f+' */\n'+read(f) for f in core)+'\n;\nwindow.restaurantBootLoading126=false;document.dispatchEvent(new Event("restaurant:boot126"));window.restaurantCoreReady143=true;\n')
boot=read('scripts/restaurant-bootstrap142.js').replace('142','143')
write('scripts/restaurant-bootstrap143.js',boot)
write('restaurant-sw143.js',read('restaurant-sw142.js').replace('142','143'))
for name in ['index.html','back-office/index.html']:
 s=read(name)
 s=re.sub(r'<script id="restaurantBoot\d+">.*?</script>','<script id="restaurantBoot143">'+boot+'</script>',s,flags=re.S)
 s=re.sub(r'<meta name="restaurant-release" content="[^"]+">','<meta name="restaurant-release" content="2026-10-22-sales-profitability-143">',s)
 write(name,s)
print('Built Sales release 143; existing login, shell CSS and POS bundles retained.')
