"""Build the Word of Hope release without changing other restaurant modules."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
def read(p):return (root/p).read_text()
def write(p,s):(root/p).write_text(s)
core=['vendor/supabase-2.118.0.js','scripts/supabase-config.js','scripts/workspace-config123.js','scripts/restaurant-auth123.js','scripts/restaurant-backoffice.js','scripts/restaurant-permissions125.js','scripts/restaurant-modules125.js','scripts/restaurant-shell122.js','scripts/workspace-links123.js','scripts/restaurant-accounting124.js','scripts/restaurant-data144.js','scripts/restaurant-home139.js','scripts/word-of-hope183.js']
write('scripts/restaurant-core145.bundle.js','/* Generated by tools/build-hope145.py. */\nwindow.restaurantBootLoading126=true;\n'+'\n;\n'.join('/* '+f+' */\n'+read(f) for f in core)+'\n;\nwindow.restaurantBootLoading126=false;document.dispatchEvent(new Event("restaurant:boot126"));window.restaurantCoreReady145=true;')
boot=read('scripts/restaurant-bootstrap144.js').replace('144','145')
write('scripts/restaurant-bootstrap145.js',boot)
write('restaurant-sw145.js',read('restaurant-sw144.js').replace('144','145'))
for f in ['index.html','back-office/index.html']:
 s=read(f)
 s=re.sub(r'<script id="restaurantBoot\d+">.*?</script>','<script id="restaurantBoot145">'+boot+'</script>',s,flags=re.S)
 s=re.sub(r'<meta name="restaurant-release" content="[^"]+">','<meta name="restaurant-release" content="2026-10-26-word-of-hope-145">',s)
 write(f,s)
print('Built release 145; preserved other modules and styling.')
