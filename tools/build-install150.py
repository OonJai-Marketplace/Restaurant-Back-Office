"""Build independently installable company Restaurant and POS entry points."""
from pathlib import Path
import json
import re
import sys

root = Path(__file__).resolve().parents[1]
check = '--check' in sys.argv
def read(path):
    return (root / path).read_text()
def emit(path, content):
    if check:
        assert read(path) == content, 'Rebuild ' + path
    else:
        (root / path).write_text(content)
def bundle(target, files, prefix='', suffix=''):
    emit(target, '/* Generated by tools/build-install150.py. */\n' + prefix + '\n' + '\n;\n'.join('/* ' + f + ' */\n' + read(f) for f in files) + '\n;\n' + suffix)

core = ['vendor/supabase-2.118.0.js', 'scripts/supabase-config.js', 'scripts/workspace-config123.js', 'scripts/restaurant-auth123.js', 'scripts/restaurant-backoffice.js', 'scripts/restaurant-permissions125.js', 'scripts/restaurant-modules125.js', 'scripts/restaurant-shell122.js', 'scripts/workspace-links123.js', 'scripts/restaurant-accounting124.js', 'scripts/restaurant-data144.js', 'scripts/restaurant-home139.js', 'scripts/word-of-hope183.js']
bundle('scripts/restaurant-core150.bundle.js', core, 'window.restaurantBootLoading126=true;', 'window.restaurantBootLoading126=false;document.dispatchEvent(new Event("restaurant:boot126"));window.restaurantCoreReady150=true;')
bundle('scripts/restaurant-pos150.bundle.js', ['scripts/pos-offline-v119.js', 'scripts/pos-performance125.js', 'scripts/pos-promotions146.js', 'scripts/pos-v118.js'])
emit('restaurant-sw150.js', read('restaurant-sw148.js').replace('148', '150'))

office = read('back-office/index.html')
office = re.sub(r'<script id="restaurantBoot\d+">.*?</script>', lambda _: '<script id="restaurantBoot150">' + read('scripts/restaurant-bootstrap150.js') + '</script>', office, flags=re.S)
office = re.sub(r'<meta name="restaurant-release" content="[^"]+">', '<meta name="restaurant-release" content="2026-10-31-install-150">', office)
office = office.replace('manifest.webmanifest?v=icons149', 'manifest.webmanifest?v=150')
if 'apple-mobile-web-app-title' not in office:
    office = office.replace('</head>', '<meta name="apple-mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-title" content="Restaurant"></head>')
emit('back-office/index.html', office)
emit('index.html', office.replace('\n<base href="../">', '', 1))

# POS retains the shared authenticated engine, but has its own launch URL,
# manifest identity and scope. No redirect into the back-office app.
pos = office.replace('<title>Oon Jai Restaurant Back Office</title>', '<title>Oon Jai POS</title>')
pos = pos.replace('<h1>Oon Jai Restaurant</h1>', '<h1>Oon Jai POS</h1>')
pos = pos.replace('href="manifest.webmanifest?v=150"', 'href="pos/manifest.webmanifest?v=150"')
pos = pos.replace('name="apple-mobile-web-app-title" content="Restaurant"', 'name="apple-mobile-web-app-title" content="POS"')
pos = pos.replace('<meta charset="utf-8"/>', '<meta charset="utf-8"/><script>const posLaunch150=new URL(location.href);posLaunch150.searchParams.set("workspace","pos");history.replaceState(history.state,"",posLaunch150);</script>', 1)
emit('pos/index.html', pos)
manifest = json.loads(read('manifest.webmanifest'))
manifest['id'] = './'
emit('manifest.webmanifest', json.dumps(manifest, indent=2) + '\n')
pos_manifest = dict(manifest, id='./', name='Oon Jai POS', short_name='POS', description='Oon Jai cashier workspace, orders and sales.', start_url='./?workspace=pos', scope='./')
pos_manifest['icons'] = [dict(icon, src='../' + icon['src']) for icon in manifest['icons']]
emit('pos/manifest.webmanifest', json.dumps(pos_manifest, indent=2) + '\n')
print('Restaurant / POS install entries and generated assets agree')
