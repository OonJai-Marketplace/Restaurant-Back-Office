for group,files in {'inventory':['inventory-menu-v104.js','item-icons-v109.js','restaurant-integration132.js'],'settings':['public-content127.js','restaurant-settings125.js'],'pos':['pos-offline-v119.js','pos-performance125.js','pos-v118.js']}.items():
    bundle('scripts/restaurant-'+group+'144.bundle.js',['scripts/'+f for f in files])
boot=read('scripts/restaurant-bootstrap143.js').replace('143','144')
write('scripts/restaurant-bootstrap144.js',boot)
write('restaurant-sw144.js',read('restaurant-sw143.js').replace('143','144'))
